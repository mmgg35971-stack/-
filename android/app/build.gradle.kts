// Public client configuration (NOT secrets): Supabase URL, the public anon key
// (protected by RLS) and the Google *Web* OAuth client id. Read from
// local.properties, Gradle properties or environment variables.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun config(name: String): String =
    (localProps.getProperty(name) ?: providers.gradleProperty(name).orNull ?: System.getenv(name) ?: "")
        .replace("\"", "")

